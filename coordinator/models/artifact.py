"""
Model manifests, versions, datasets, and output artifact models.
"""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING, Any

from sqlalchemy import BigInteger, Boolean, DateTime, ForeignKey, Integer, String, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from coordinator.database import Base
from coordinator.models.base import TimestampMixin, UUIDMixin

if TYPE_CHECKING:
    from coordinator.models.job import Job
    from coordinator.models.user import User


class ModelManifest(Base, UUIDMixin, TimestampMixin):
    """Metadata record defining an AI model architecture and hardware requirements."""

    __tablename__ = "model_manifests"

    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    name: Mapped[str] = mapped_column(String(128), unique=True, index=True, nullable=False)
    description: Mapped[str | None] = mapped_column(String(1024), nullable=True)
    architecture: Mapped[str] = mapped_column(
        String(64), nullable=False
    )  # e.g., "LlamaForCausalLM"
    framework: Mapped[str] = mapped_column(String(32), default="transformers", nullable=False)
    format: Mapped[str] = mapped_column(String(32), default="safetensors", nullable=False)
    parameter_count: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    default_vram_required_mb: Mapped[int] = mapped_column(Integer, default=16384, nullable=False)
    is_public: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    # Relationships
    user: Mapped["User"] = relationship("User", back_populates="model_manifests")
    versions: Mapped[list["ModelVersion"]] = relationship(
        "ModelVersion", back_populates="manifest", cascade="all, delete-orphan"
    )
    jobs: Mapped[list["Job"]] = relationship("Job", back_populates="model")


class ModelVersion(Base, UUIDMixin):
    """Versioned immutable weights file or tensor bundle stored in S3/MinIO."""

    __tablename__ = "model_versions"

    model_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("model_manifests.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    version_tag: Mapped[str] = mapped_column(String(32), default="v1.0.0", nullable=False)
    storage_path: Mapped[str] = mapped_column(String(512), nullable=False)
    checksum_sha256: Mapped[str] = mapped_column(String(64), nullable=False)
    size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    tensor_metadata: Mapped[dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    is_ready: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    # Relationships
    manifest: Mapped["ModelManifest"] = relationship("ModelManifest", back_populates="versions")


class Dataset(Base, UUIDMixin, TimestampMixin):
    """Fine-tuning or evaluation dataset cataloged in MinIO."""

    __tablename__ = "datasets"

    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    name: Mapped[str] = mapped_column(String(128), index=True, nullable=False)
    description: Mapped[str | None] = mapped_column(String(1024), nullable=True)
    format: Mapped[str] = mapped_column(String(32), default="jsonl", nullable=False)
    num_records: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    storage_path: Mapped[str] = mapped_column(String(512), nullable=False)
    checksum_sha256: Mapped[str] = mapped_column(String(64), nullable=False)
    is_validated: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    # Relationships
    user: Mapped["User"] = relationship("User", back_populates="datasets")
    jobs: Mapped[list["Job"]] = relationship("Job", back_populates="dataset")


class Artifact(Base, UUIDMixin):
    """Execution artifact generated by jobs: checkpoints, adapters, images, logs."""

    __tablename__ = "artifacts"

    job_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("jobs.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    artifact_type: Mapped[str] = mapped_column(String(32), nullable=False, index=True)
    storage_path: Mapped[str] = mapped_column(String(512), nullable=False)
    filename: Mapped[str] = mapped_column(String(255), nullable=False)
    size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    checksum_sha256: Mapped[str] = mapped_column(String(64), nullable=False)
    mime_type: Mapped[str] = mapped_column(
        String(64), default="application/octet-stream", nullable=False
    )
    metadata_json: Mapped[dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    # Relationships
    job: Mapped["Job | None"] = relationship("Job", back_populates="artifacts")
    user: Mapped["User"] = relationship("User", back_populates="artifacts")
